/*
 * 🛑 警告: 「N個の条件(N<=20)を満たす集合の数え上げ」にコピペしてはいけません！
 * それは一般の包除原理（Bit全探索）の出番です。
 *
 * 【メビウス関数（数論的包除原理）】
 * [適性対象] 「倍数・約数」「素因数」を条件とする数え上げ（GCD=X, 互いに素など）
 * [制約目安] N <= 10^6 クラス（Bit全探索では到底不可能なサイズ）
 * [役割]     整数 x が持つ素因数の種類数 k に応じて、包除原理の足し引きの符号 (-1)^k を配列として事前計算する。
 *
 * [具体例] 1〜Nの中から互いに素な(GCD=1)ペアを選ぶ場合:
 * ans = Σ( mu[d] * (dの倍数の個数 C 2) ) 
 * 
 * d=1(何も選ばない): +1
 * d=2,3,5(素数): -1 (偶数や3の倍数を引く)
 * d=6(素因数2つ): +1 (2の倍数かつ3の倍数を足し戻す)
 * d=4(平方因子): 0 (4の倍数は2の倍数として処理済みなので無視)
 */
int mu_size = n + 1; // サイズは問題によって変えてください。
vector<int> mu(mu_size + 1), prime, iscomp(mu_size + 1, 0);

mu[1] = 1; // どの素因数も含まない（条件を1つも選ばないベースの状態）

for(int i = 2; i <= mu_size; i++){
    if(!iscomp[i]){ 
        // 素数の場合：素因数が i のみ（奇数個）なので、包除原理の「引き算」フェーズ
        prime.push_back(i);
        mu[i] = -1; 
    }
    for(int p : prime){
        if(1LL * i * p > mu_size) break; // 探索範囲を超えたら打ち切り
        iscomp[i * p] = 1;
        
        if(i % p == 0){ 
            // 平方因子を持つ場合（例: p^2 の倍数）：
            // 同じ条件を2回適用することになり、包除原理の足し引きに寄与しないため 0
            mu[i * p] = 0;
            break;
        } else {
            // 素因数 p が1つ追加されるごとに、包除原理の足し引き（奇数個と偶数個）が反転する
            mu[i * p] = -mu[i]; 
        }
    }
}
